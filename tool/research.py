"""Companion's read-only research adapter; all source generations live in one DB."""
from pathlib import Path
from types import SimpleNamespace
from bisect import bisect_right
import json
import re

from ifs_research.common import database, digest, dump, now, ResearchError
from ifs_research.code_store import CodeStore, routines, clean_vb
from ifs_research.structure import StructureStore
from ifs_research.wiki_store import WikiStore
from ifs_research.retrieval import RetrievalStore


class SnapshotCode(CodeStore):
    def read(self, path, start=1, end=None, snapshot=None):
        result = super().read(path, start, end, snapshot)
        with database(self.path) as db:
            row = db.execute('SELECT source,original_path FROM source_locations WHERE path=?', (path,)).fetchone()
        if row:
            original = Path(row['source']) / row['original_path']
            result['local_source'] = str(original)
            try: result['local_source_matches_snapshot'] = digest(original.read_bytes()) == result['sha256']
            except OSError: result['local_source_matches_snapshot'] = False
        return result


class Research:
    def __init__(self, index, bundle):
        self.config = SimpleNamespace(workspace=Path(index).parent)
        self.code = SnapshotCode(Path(index))
        self.wiki = WikiStore(Path(index))
        self.structure = StructureStore(self.code)
        self.model_path = Path(bundle)/'embedding-model'
        if not self.model_path.exists(): self.model_path=Path(bundle).parent/'workspace/model'
        self.retrieval = RetrievalStore(self)

    def dispatch(self, name, args):
        """Explicit read-only allowlist. Arguments never become file or SQL commands."""
        if not isinstance(args, dict): raise ResearchError('Tool arguments must be an object')
        methods = {
            'search': self.retrieval.search, 'code_search': self.code.search,
            'code_read': self.code.read, 'find_routines': self.code.find_routines,
            'read_routine': self.code.read_routine, 'symbol_lookup': self.structure.lookup,
            'routine_context': self.structure.context, 'wiki_search': self.wiki.search,
            'wiki_read': self.wiki.read, 'wiki_source': self.wiki.source,
        }
        if name not in methods: raise ResearchError('Unknown research tool')
        if any(k in args for k in ('corpus','snapshot')):
            # Only the active source generation can be investigated.
            if name != 'wiki_source': raise ResearchError('Use the active source snapshot')
        for key in ('limit','length','start','end','offset'):
            if key in args and (type(args[key]) is not int or args[key] < (1 if key in ('limit','length','start','end') else 0)):
                raise ResearchError('Invalid range argument')
        if 'limit' in args: args = {**args, 'limit': min(args['limit'],20)}
        return methods[name](**args)


def prepare_research(index, bundle):
    r = Research(index, bundle)
    with database(index) as db:
        inventory = db.execute('SELECT * FROM files ORDER BY source,path').fetchall()
        files = [f for f in inventory if not any(p.lower() in ('tmpcode','backup','backups','reference','ref') for p in Path(f['path']).parts)
                 and '<auto-generated' not in f['body'][:2000].lower()]
        if not files: raise ResearchError('No active source files remain after excluding temporary/generated code.')
        roots = sorted({f['source'] for f in files})
        labels = {root: f'{i+1}-{Path(root).name}' for i,root in enumerate(roots)}
        manifest = [{'path': labels[f['source']]+'/'+f['path'], 'sha256': f['sha256']} for f in files]
        sid = digest(dump(manifest))
        db.execute('INSERT INTO code_snapshots VALUES(?,?,?,?)', (sid,'',now(),dump({'files':manifest})))
        db.execute('INSERT INTO code_current VALUES(1,?)',(sid,))
        db.execute('CREATE TABLE source_locations(path TEXT PRIMARY KEY,source TEXT,original_path TEXT)')
        for f, item in zip(files,manifest):
            path = item['path']; lines=f['body'].splitlines()
            db.execute('INSERT INTO source_locations VALUES(?,?,?)',(path,f['source'],f['path']))
            db.execute('INSERT INTO code_files VALUES(?,?,?,?,?)',(sid,path,f['sha256'],'decoded source snapshot',f['body']))
            rs = routines(lines) if path.lower().endswith('.vb') else []
            for routine in rs:
                db.execute('INSERT INTO code_routines VALUES(?,?,?,?,?,?,?,?)',
                    (f"{sid}:{path}:{routine['start']}",sid,path,routine['name'],routine['kind'],routine['start'],routine['end'],routine['boundary_warning']))
            starts=[v['start'] for v in rs]; records=[]
            for n,line in enumerate(lines,1):
                if not line.strip(): continue
                i=bisect_right(starts,n)-1
                rid=f"{sid}:{path}:{rs[i]['start']}" if i>=0 and n<=rs[i]['end'] else None
                clean=clean_vb(line) if path.lower().endswith('.vb') else re.sub(r'"(?:\\.|[^"\\])*"|//.*',' ',line)
                records.append((sid,path,n,rid,clean,line))
            db.executemany('INSERT INTO code_fts VALUES(?,?,?,?,?,?)',records)
    wiki_path = Path(bundle)/'wiki'
    manifest_path=wiki_path/'manifest.json'
    wiki_manifest=json.loads(manifest_path.read_text(encoding='utf-8')) if manifest_path.exists() else {'pages':[]}
    for item in wiki_manifest['pages']:
        file=(wiki_path/item['file']).resolve()
        if not file.is_relative_to(wiki_path.resolve()): raise ResearchError('Invalid wiki snapshot path')
        raw=file.read_bytes()
        if digest(raw)!=item['sha256']: raise ResearchError('Wiki snapshot failed its integrity check')
        page=json.loads(raw);r.wiki.put(page)
        r.wiki.mark(page['title'],'offline','Bundled snapshot; approval and freshness have not been checked live.')
    corpus=r.retrieval.build()
    return {'snapshot':sid,'corpus':corpus,'research_files':len(files),'excluded_research_files':len(inventory)-len(files),'wiki_pages':len(wiki_manifest['pages']),
            'wiki_dates':sorted({p['fetched_at'][:10] for p in wiki_manifest['pages']}),
            'wiki_bundle':digest(manifest_path.read_bytes()) if manifest_path.exists() else None,
            'research_version':1,'semantic_ready':False}


def evidence_from_hits(research, query):
    # Code and documentation have very different corpus sizes. Reserve places for
    # each so numerous short code matches cannot hide relevant wiki passages.
    result=research.retrieval.search(query,limit=6,kind='code')
    docs=research.retrieval.search(query,limit=3,kind='wiki')
    evidence=[]
    for hit in [*result['hits'],*docs['hits']]:
        if hit['kind']=='code':
            c=hit['citation']; item=research.code.read(c['path'],c['start'],min(c['end'],c['start']+199))
            item['kind']='code';item['source']=item['local_source']
        else:
            item=research.wiki.read(hit['section_id'],offset=hit['offset'],length=4000)
            item['kind']='wiki'
        evidence.append({**item,'id':f'E{len(evidence)+1}'})
    return evidence,result['semantic_status']
